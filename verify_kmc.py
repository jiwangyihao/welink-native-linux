def build_driver(directory):
    driver = Path(directory) / "native-kmc-driver"
    subprocess.run(
        [os.environ.get("CC", "gcc"), "-m32", "-O2", "-Wall", "-Wextra",
         "-x", "c", "-", "-o", str(driver), "-ldl"],
        input=DRIVER_SOURCE, text=True, check=True, capture_output=True, timeout=30,
    )
    return driver


def invoke(driver, library, requests, log):
    completed = subprocess.run(
        [str(driver), str(library)],
        input="".join(json.dumps(row, ensure_ascii=False) + "\n" for row in requests),
        env=dict(os.environ, WELINK_NATIVE_LOG=str(log)),
        text=True, check=True, capture_output=True, timeout=30,
    )
    replies = [json.loads(line) for line in completed.stdout.splitlines()]
    assert len(replies) == len(requests), completed.stdout
    for request, reply in zip(requests, replies):
        assert reply["rsp"] == request["cmd"] and reply["sno"] == request["sno"]
    return replies


def encryption(directory, plaintext, sno):
    raw = plaintext.encode("utf-8") if isinstance(plaintext, str) else plaintext
    return {"cmd": 106, "sno": sno, "param": {
        "kmcdir": str(directory), "plainText": base64.b64encode(raw).decode("ascii")}}


def decryption(directory, ciphertext, sno):
    return {"cmd": 107, "sno": sno, "param": {
        "kmcdir": str(directory), "cipherText": ciphertext}}


def install_fixture(directory, data=STORE):
    directory.mkdir()
    for name in STORE_NAMES:
        path = directory / name
        path.write_bytes(data)
        path.chmod(0o600)


def verify(library, driver, work):
    work = Path(work)
    log = work / "native.log"
    call = lambda requests: invoke(driver, library, requests, log)
    vendor = work / "vendor"
    install_fixture(vendor)
    fixed = call([decryption(vendor, CIPHER, 1)])[0]
    assert fixed["result"] == 0 and fixed["param"] == {"PlainText": PLAINTEXT}

    samples = ["B" * n for n in (1, 15, 16, 17, 31, 32, 48)]
    samples += ['中文"\\\n', "中" * 63, "L" * 189, "A\x00B", "B" * 16]
    encrypted = call([encryption(vendor, plain, i + 10) for i, plain in enumerate(samples)])
    ciphertexts = []
    for plain, reply in zip(samples, encrypted):
        assert reply["result"] == 0, reply
        assert set(reply["param"]) == {"CiperText", "CiperLen"}, reply
        ciphertext = reply["param"]["CiperText"]
        binary = bytes.fromhex(ciphertext)
        assert struct.unpack_from(">5I", binary) == (2, 0, 0, 1, 7)
        assert struct.unpack_from(">I", binary, 60)[0] == len(binary) - 64
        assert reply["param"]["CiperLen"] == 4 * len(binary)
        ciphertexts.append(ciphertext)
    assert ciphertexts[2] != ciphertexts[-1], "repeated plaintext reused a ciphertext"
    decoded = call([decryption(vendor, cipher, i + 100) for i, cipher in enumerate(ciphertexts)])
    assert [reply["param"]["PlainText"] for reply in decoded] == [s.split("\x00", 1)[0] for s in samples]
    assert all((vendor / name).read_bytes() == STORE for name in STORE_NAMES)

    empty = encryption(vendor, "", 200)
    invalid = encryption(vendor, "unused", 201)
    invalid["param"]["plainText"] = "!!!!"
    failures = call([empty, invalid, decryption(vendor, "not hex", 202)])
    assert failures[0]["result"] == 3 and failures[0]["param"] == {"CiperText": "", "CiperLen": 0}
    assert failures[1]["result"] == 1 and failures[1]["param"] == {"CiperText": "", "CiperLen": 0}
    assert failures[2]["result"] == 0 and failures[2]["param"] == {"PlainText": ""}

    # Keep oversized inputs covered: compatibility means the original error,
    # not a successful native-only roundtrip outside the wrapper's contract.
    oversized = call([encryption(vendor, text, 203 + i) for i, text in enumerate(
        ("L" * 190, "L" * 8193, "中" * 64, b"A\0" + b"Z" * 300))])
    assert all(row["result"] == 1 and row["param"] == {"CiperText": "", "CiperLen": 0}
               for row in oversized)
    limits = call([decryption(vendor, CIPHER_AT_DECRYPT_LIMIT, 207),
                   decryption(vendor, CIPHER_PAST_DECRYPT_LIMIT, 208)])
    assert limits[0]["result"] == 0 and limits[0]["param"]["PlainText"] == "V" * 239
    assert limits[1]["result"] == 0 and limits[1]["param"]["PlainText"] == ""

    created = work / "created"
    created.mkdir()
    generated = call([encryption(created, "new-native-store", 210)])[0]
    assert generated["result"] == 0
    new_cipher = generated["param"]["CiperText"]
    assert call([decryption(created, new_cipher, 211)])[0]["param"]["PlainText"] == "new-native-store"
    assert call([decryption(created, CIPHER, 212)])[0]["param"]["PlainText"] == ""
    paths = [created / name for name in STORE_NAMES]
    assert paths[0].read_bytes() == paths[1].read_bytes()
    assert all(stat.S_IMODE(path.stat().st_mode) == 0o600 for path in paths)
    assert paths[0].stat().st_ino != paths[1].stat().st_ino, "backup shares primary inode"
    paths[0].write_bytes(b"broken primary")
    assert call([decryption(created, new_cipher, 213)])[0]["param"]["PlainText"] == "new-native-store"
    assert paths[0].read_bytes() == b"broken primary", "read unexpectedly repaired an existing store"

    absent = work / "absent"
    absent.mkdir()
    assert call([decryption(absent, CIPHER, 220)])[0]["param"]["PlainText"] == ""
    assert not list(absent.iterdir()), "decrypt generated replacement keys"
    corrupt_cases = []
    for label, offset in (("root-checksum", 0x38), ("master-hmac", 0x1e0)):
        damaged = bytearray(STORE)
        damaged[offset] ^= 1
        directory = work / label
        install_fixture(directory, damaged)
        reply = call([encryption(directory, "must not replace keys", 230)])[0]
        assert reply["result"] != 0 and reply["param"]["CiperText"] == "", reply
        assert all((directory / name).read_bytes() == damaged for name in STORE_NAMES)
        corrupt_cases.append(label)

    racing = work / "racing"
    racing.mkdir()
    def create_one(i):
        return call([encryption(racing, f"parallel-{i}", 300 + i)])[0]
    with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
        raced = list(pool.map(create_one, range(4)))
    assert all(reply["result"] == 0 for reply in raced)
    recovered = call([decryption(racing, row["param"]["CiperText"], 400 + i)
                      for i, row in enumerate(raced)])
    assert [row["param"]["PlainText"] for row in recovered] == [f"parallel-{i}" for i in range(4)]
    assert (racing / STORE_NAMES[0]).read_bytes() == (racing / STORE_NAMES[1]).read_bytes()

    unknown = call([{"cmd": 999999, "sno": 500, "param": {}}])[0]
    assert unknown["result"] != 0, "unsupported command claimed success"
    log_text = log.read_text()
    assert PLAINTEXT not in log_text and base64.b64encode(samples[8].encode()).decode() not in log_text
    return {"passed": True, "native_bits": 32, "vendor_fixture": True,
            "roundtrips": len(samples), "concurrent_creators": 4,
            "corrupt_store_cases": corrupt_cases, "backup_recovery": True,
            "vendor_wrapper_limits": True,
            "wrong_store_rejected": True, "decrypt_does_not_create_keys": True}


